async def seed_blog():
    """Добавление статей в блог."""
    engine = create_async_engine(settings.DATABASE_URL)
    async_session = sessionmaker(engine, class_=AsyncSession, expire_on_commit=False)

    async with async_session() as session:
        for article in ARTICLES:
            # Проверяем, существует ли статья
            stmt = select(BlogPost).where(BlogPost.slug == article["slug"])
            result = await session.execute(stmt)
            existing = result.scalar_one_or_none()

            if existing:
                # Старым статьям проставляем рубрику, если её не было
                if not existing.category and article.get("category"):
                    existing.category = article["category"]
                    print(f"Рубрика добавлена: '{article['title']}' -> {article['category']}")
                else:
                    print(f"Статья '{article['title']}' уже существует, пропускаем")
                continue

            # Создаём новую статью
            post = BlogPost(
                title=article["title"],
                slug=article["slug"],
                excerpt=article["excerpt"],
                content=article["content"],
                category=article.get("category"),
                is_published=True,
                published_at=datetime.now(timezone.utc),
            )
            session.add(post)
            print(f"Добавлена статья: {article['title']}")

        await session.commit()
        print("\nВсе статьи успешно добавлены!")

    await engine.dispose()


if __name__ == "__main__":
    asyncio.run(seed_blog())
